// Tech tree: six fields, ten tiers. Names, descriptions and quotes are original to this game.
import type { ResearchField } from "../types";

export type TechEffect =
  | { stat: "range"; value: number }          // + light-years of fuel range
  | { stat: "speed"; value: number }          // ship speed in ly/turn (highest known applies)
  | { stat: "hostility"; value: number }      // + levels of harsher planets you can settle
  | { stat: "terraform"; value: number }      // + population capacity on every owned planet
  | { stat: "growth"; value: number }         // + fraction of population growth, e.g. 0.25 = +25%
  | { stat: "popCost"; value: number }        // change to the BC cost of buying 1 population (negative = cheaper)
  | { stat: "productivity"; value: number }   // + BC produced per population unit
  | { stat: "robotControls"; value: number }  // + factories each population unit can run
  | { stat: "factoryCost"; value: number }    // change to base factory cost (negative = cheaper)
  | { stat: "scan"; value: number }           // + light-years of scanner range
  | { stat: "research"; value: number }       // + fraction of research output, e.g. 0.1 = +10%
  | { stat: "computer"; value: number }       // ship targeting computer level (highest known applies)
  | { stat: "ecm"; value: number }            // ship jammer level (highest known applies)
  | { stat: "armor"; value: number }          // ship armor level (highest known applies)
  | { stat: "shield"; value: number }         // ship shield level (highest known applies)
  | { stat: "planetShield"; value: number }   // planetary shield strength (highest known applies)
  | { stat: "weapon"; kind: "beam" | "missile" | "bomb" | "torpedo"; min: number; max: number }
  | { stat: "special"; key: string };         // unlocks a special ability used later

export interface Tech {
  id: string;          // kebab-case, unique, e.g. "deuterium-cells"
  name: string;
  field: ResearchField; // "computers" | "construction" | "forceFields" | "planetology" | "propulsion" | "weapons"
  tier: number;        // 1..10
  start?: boolean;     // true = every empire knows it at the start of the game
  effects: TechEffect[];
  description: string; // one plain sentence saying what it does in the game, under 20 words
  quote: string;       // one short in-universe quote (under 25 words) with an invented speaker, e.g. "— Archivist Venn of the Vossari"
}

